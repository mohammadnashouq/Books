// SQLite database: schema, migrations and connection setup.
// Uses Node's built-in node:sqlite (no native add-ons to compile).

import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { DatabaseSync } from 'node:sqlite';

/** Each entry upgrades the schema by one version (PRAGMA user_version). */
const MIGRATIONS = [
  `
  CREATE TABLE users (
    id            INTEGER PRIMARY KEY,
    username      TEXT NOT NULL,
    username_key  TEXT NOT NULL UNIQUE,      -- lower-cased, for case-insensitive uniqueness
    password_hash TEXT NOT NULL,
    created_at    TEXT NOT NULL
  );

  CREATE TABLE sessions (
    token_hash  TEXT PRIMARY KEY,            -- sha256 of the cookie value; the raw token is never stored
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TEXT NOT NULL,
    expires_at  TEXT NOT NULL
  );
  CREATE INDEX sessions_user ON sessions(user_id);

  CREATE TABLE books (
    id          TEXT PRIMARY KEY,            -- generated by the client (UUID)
    owner_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    genre       TEXT NOT NULL DEFAULT '',
    status      TEXT NOT NULL,
    goal        INTEGER NOT NULL DEFAULT 0,
    color       TEXT NOT NULL,
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,
    revision    INTEGER NOT NULL DEFAULT 1   -- bumped on every write; used to detect stale saves
  );
  CREATE INDEX books_owner ON books(owner_id);

  CREATE TABLE chapters (
    book_id   TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    id        TEXT NOT NULL,
    position  INTEGER NOT NULL,
    title     TEXT NOT NULL DEFAULT '',
    text      TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (book_id, id)
  );

  CREATE TABLE comments (
    book_id     TEXT NOT NULL,
    id          TEXT NOT NULL,
    chapter_id  TEXT NOT NULL,
    position    INTEGER NOT NULL,
    author      TEXT NOT NULL,
    text        TEXT NOT NULL,
    quote       TEXT NOT NULL DEFAULT '',
    resolved    INTEGER NOT NULL DEFAULT 0,
    created_at  TEXT NOT NULL,
    PRIMARY KEY (book_id, id),
    FOREIGN KEY (book_id, chapter_id) REFERENCES chapters(book_id, id) ON DELETE CASCADE
  );
  `,
];

export const SCHEMA_VERSION = MIGRATIONS.length;

export function openDatabase(path = ':memory:') {
  if (path !== ':memory:') mkdirSync(dirname(path), { recursive: true });
  const db = new DatabaseSync(path);
  db.exec('PRAGMA foreign_keys = ON');
  db.exec('PRAGMA busy_timeout = 5000');
  if (path !== ':memory:') db.exec('PRAGMA journal_mode = WAL');
  migrate(db);
  return db;
}

export function migrate(db) {
  const current = db.prepare('PRAGMA user_version').get().user_version;
  if (current > MIGRATIONS.length) {
    throw new Error(`Database schema v${current} is newer than this server (v${MIGRATIONS.length}).`);
  }
  for (let v = current; v < MIGRATIONS.length; v += 1) {
    transaction(db, () => {
      db.exec(MIGRATIONS[v]);
      db.exec(`PRAGMA user_version = ${v + 1}`);
    });
  }
}

/** Run fn inside a transaction; roll back if it throws. */
export function transaction(db, fn) {
  db.exec('BEGIN IMMEDIATE');
  try {
    const result = fn();
    db.exec('COMMIT');
    return result;
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
}
